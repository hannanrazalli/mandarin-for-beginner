#!/usr/bin/env python3
"""Generate trusted operator SQL from the reviewed curriculum; no database access."""
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]

def q(value):
    if value is None:
        return 'null'
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"

def slug(value):
    if not isinstance(value, str) or not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', value) or len(value) > 80:
        raise ValueError(f'Invalid authored slug: {value!r}')
    return value

def main():
    index = json.loads((ROOT / 'content/index.json').read_text())
    units = sorted(index['units'], key=lambda u: u['position'])
    lessons = {}
    for unit in units:
        slug(unit['id'])
        for lesson_id in unit['lesson_ids']:
            slug(lesson_id)
            if lesson_id in lessons:
                raise ValueError('Duplicate lesson in index')
            lesson = json.loads((ROOT / 'content/lessons' / f'{lesson_id}.json').read_text())
            if lesson['id'] != lesson_id or lesson['unit'] != unit['position'] or lesson['schema_version'] != 1:
                raise ValueError('Lesson/index contract mismatch')
            if type(lesson.get('content_version')) is not int or lesson['content_version'] < 1:
                raise ValueError(f'{lesson_id}: content_version must be a positive integer')
            if not 1 <= len(lesson['items']) <= 20 or len({i['id'] for i in lesson['items']}) != len(lesson['items']):
                raise ValueError('Invalid item count or duplicate item IDs')
            for item in lesson['items']:
                slug(item['id'])
                if type(item['needs_review']) is not bool:
                    raise ValueError('Missing explicit semantic approval')
            lessons[lesson_id] = lesson
    out = ['-- Generated by supabase/scripts/generate_seed.py; trusted operator only.',
           '-- Synthetic TTS may still need audio review; semantic approval is independent.',
           'begin;', 'set local standard_conforming_strings = on;',
           'select pg_catalog.pg_advisory_xact_lock(78421,1);']
    previous_unit = None
    for unit in units:
        unit_slug = q(unit['id'])
        prerequisite = 'null' if previous_unit is None else f'(select id from public.units where slug={q(previous_unit)})'
        version = max(lessons[i]['content_version'] for i in unit['lesson_ids'])
        out.append(f'''insert into public.units(slug,position,title_ms,title_en,content_version,published,prerequisite_unit_id)
values ({unit_slug},{q(unit['position'])},{q(unit['title_ms'])},{q(unit['title_en'])},{version},true,{prerequisite})
on conflict(slug) do update set title_ms=excluded.title_ms,title_en=excluded.title_en,
content_version=excluded.content_version,published=true,prerequisite_unit_id=excluded.prerequisite_unit_id;''')
        previous_unit = unit['id']
        for position, lesson_id in enumerate(unit['lesson_ids']):
            lesson = lessons[lesson_id]
            lesson_slug = q(lesson_id)
            lookup = f'(select id from public.lessons where slug={lesson_slug})'
            version = lesson['content_version']
            kinds = {i['kind'] for i in lesson['items']}
            kind = next(iter(kinds)) if len(kinds) == 1 else 'mixed'
            approved = all(not i['needs_review'] for i in lesson['items'])
            out.append(f'''insert into public.lessons(slug,unit_id,position,title_ms,title_en,kind,duration_seconds,content_path,content_version,published)
values ({lesson_slug},(select id from public.units where slug={unit_slug}),{position},{q(lesson['title_ms'])},{q(lesson['title_ms'])},{q(kind)},{lesson['duration_seconds']},{q('content/lessons/'+lesson_id+'.json')},{version},false)
on conflict(slug) do update set title_ms=excluded.title_ms,title_en=excluded.title_en,kind=excluded.kind,
duration_seconds=excluded.duration_seconds,content_path=excluded.content_path,content_version=excluded.content_version,published=false;''')
            keys = []
            for item_position, item in enumerate(lesson['items']):
                answer = item['pinyin'] if item['kind'] == 'pronunciation' else item['meaning_ms']
                keys.append({'item_id': item['id'], 'correct_answer': answer, 'needs_review': item['needs_review']})
                if item['kind'] != 'vocabulary':
                    continue
                ex = item['example']
                fields = ['slug','hanzi','pinyin','meaning_ms','example_hanzi','example_pinyin','example_ms','tone_note_ms','topic','hsk_level','hsk_edition','source','content_version','needs_review']
                values = [item['id'],item['hanzi'],item['pinyin'],item['meaning_ms'],ex['hanzi'],ex['pinyin'],ex['meaning_ms'],item['tone_note_ms'],item['topic'],item['hsk_level'],item['hsk_edition'],item['source'],version,item['needs_review']]
                assignments = ','.join(f'{field}=excluded.{field}' for field in fields[1:])
                out.append(f"insert into public.words({','.join(fields)}) values ({','.join(q(v) for v in values)}) on conflict(slug) do update set {assignments};")
                out.append(f"insert into public.lesson_words(lesson_id,word_id,position) values ({lookup},(select id from public.words where slug={q(item['id'])}),{item_position}) on conflict(lesson_id,word_id) do update set position=excluded.position;")
            out.append(f"select private.seed_lesson_items({lesson_slug},{version},{q(json.dumps(keys, ensure_ascii=False))}::jsonb);")
            out.append(f"update public.lessons set published={q(approved)} where slug={lesson_slug};")
    out.append('commit;')
    destination = ROOT / 'supabase/seed.sql'
    destination.write_text('\n'.join(out)+'\n')
    print(f'Generated {len(units)} units, {len(lessons)} lessons into {destination.relative_to(ROOT)}')

if __name__ == '__main__':
    main()
